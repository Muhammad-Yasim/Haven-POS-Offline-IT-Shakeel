-- ============================================================================
-- EXPENSES
-- ============================================================================
CREATE TABLE expense_categories (
  id          INTEGER PRIMARY KEY AUTOINCREMENT,
  business_id INTEGER NOT NULL REFERENCES businesses(id) ON DELETE CASCADE,
  name        TEXT NOT NULL,
  CONSTRAINT uq_expense_categories_business_name UNIQUE (business_id, name)
);

CREATE TABLE recurring_expense_templates (
  id            INTEGER PRIMARY KEY AUTOINCREMENT,
  business_id   INTEGER NOT NULL REFERENCES businesses(id)       ON DELETE CASCADE,
  location_id   INTEGER NOT NULL REFERENCES locations(id)        ON DELETE RESTRICT,
  category_id   INTEGER NOT NULL REFERENCES expense_categories(id) ON DELETE RESTRICT,
  amount        DECIMAL(12,2) NOT NULL,
  frequency     TEXT NOT NULL,     -- 'monthly','weekly', etc.
  next_due_date TEXT NOT NULL,
  is_active     INTEGER NOT NULL DEFAULT 1 CHECK (is_active IN (0,1)),
  created_at    TEXT NOT NULL DEFAULT (strftime('%Y-%m-%dT%H:%M:%fZ','now'))
);

CREATE TABLE expenses (
  id                    INTEGER PRIMARY KEY AUTOINCREMENT,
  business_id           INTEGER NOT NULL REFERENCES businesses(id)         ON DELETE CASCADE,
  location_id           INTEGER NOT NULL REFERENCES locations(id)          ON DELETE RESTRICT,
  category_id           INTEGER NOT NULL REFERENCES expense_categories(id) ON DELETE RESTRICT,
  expense_date          TEXT NOT NULL DEFAULT (date('now','localtime')),
  expense_from_user_id  TEXT REFERENCES users(id) ON DELETE SET NULL,
  amount                DECIMAL(12,2) NOT NULL,
  note                  TEXT,
  payment_method        TEXT,
  recurring_template_id INTEGER REFERENCES recurring_expense_templates(id) ON DELETE SET NULL,
  created_at            TEXT NOT NULL DEFAULT (strftime('%Y-%m-%dT%H:%M:%fZ','now')),
  reference_number      INTEGER,
  status                TEXT CHECK (status IN ('paid','pending')),
  title                 TEXT NOT NULL,
  vendor                TEXT,
  register_id           INTEGER REFERENCES registers(id) ON DELETE SET NULL
);


-- ============================================================================
-- NOTIFICATIONS
-- ============================================================================
CREATE TABLE notifications (
  id                     INTEGER PRIMARY KEY AUTOINCREMENT,
  business_id            INTEGER NOT NULL REFERENCES businesses(id) ON DELETE CASCADE,
  type                   TEXT NOT NULL,       -- 'low_stock','invoice_due', etc.
  message                TEXT NOT NULL,
  is_read                INTEGER NOT NULL DEFAULT 0 CHECK (is_read IN (0,1)),
  related_reference_type TEXT,
  related_reference_id   INTEGER,             -- polymorphic (no FK)
  created_at             TEXT NOT NULL DEFAULT (strftime('%Y-%m-%dT%H:%M:%fZ','now'))
);


-- ============================================================================
-- INDEXES
-- Postgres did not auto-index FK columns; SQLite needs them for fast joins AND
-- for fast ON DELETE / RESTRICT checks. UNIQUE constraints above already cover
-- their own leading columns.
-- ============================================================================

CREATE INDEX idx_contacts_business_type       ON contacts (business_id, contact_type, is_active);
CREATE INDEX idx_contacts_location            ON contacts (location_id);
