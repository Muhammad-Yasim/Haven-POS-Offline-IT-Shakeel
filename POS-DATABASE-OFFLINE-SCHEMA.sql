-- KEPT on purpose: role_permissions. It costs nothing (one fixed set of module rows,
-- seeded as full-access for the owner at provisioning), and it lets the existing
-- permission-check code and future user-management work without a schema change.

CREATE TABLE role_permissions (
  id          INTEGER PRIMARY KEY AUTOINCREMENT,
  user_id     TEXT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  module      TEXT NOT NULL,   -- 'purchases','sales','products','contacts','expenses',
                               -- 'stock','reports','settings','user_management','pos'
  can_view    INTEGER NOT NULL DEFAULT 0 CHECK (can_view   IN (0,1)),
  can_create  INTEGER NOT NULL DEFAULT 0 CHECK (can_create IN (0,1)),
  can_edit    INTEGER NOT NULL DEFAULT 0 CHECK (can_edit   IN (0,1)),
  can_delete  INTEGER NOT NULL DEFAULT 0 CHECK (can_delete IN (0,1)),
  CONSTRAINT uq_role_permissions_user_module UNIQUE (user_id, module)
);


-- ============================================================================
-- CONTACTS
-- ============================================================================
CREATE TABLE contacts (
  id               INTEGER PRIMARY KEY AUTOINCREMENT,
  business_id      INTEGER NOT NULL REFERENCES businesses(id) ON DELETE CASCADE,
  contact_type     TEXT NOT NULL CHECK (contact_type IN ('customer','supplier')),
  name             TEXT NOT NULL,
  contact_number   TEXT NOT NULL,
  alternate_number TEXT,
  email            TEXT,
  landline         TEXT,
  opening_balance  DECIMAL(12,2) NOT NULL DEFAULT 0,
  city             TEXT,
  country          TEXT,
  tax_ntn_number   TEXT,           -- mainly for suppliers
  custom_fields    TEXT NOT NULL DEFAULT '{}' CHECK (json_valid(custom_fields)),
  is_active        INTEGER NOT NULL DEFAULT 1 CHECK (is_active IN (0,1)),
  created_at       TEXT NOT NULL DEFAULT (strftime('%Y-%m-%dT%H:%M:%fZ','now')),
  business_name    TEXT,
  address          TEXT,
  location_id      INTEGER REFERENCES locations(id),
  created_by       TEXT,
  UNIQUE (business_id, contact_number)
);

CREATE TABLE contact_ledger (
  id             INTEGER PRIMARY KEY AUTOINCREMENT,
  business_id    INTEGER NOT NULL REFERENCES businesses(id) ON DELETE CASCADE,
  contact_id     INTEGER NOT NULL REFERENCES contacts(id) ON DELETE RESTRICT,
  reference_type TEXT NOT NULL,    -- 'opening_balance','sale','purchase','payment','sale_return','purchase_return'
  reference_id   INTEGER,          -- polymorphic (no FK)
  amount         DECIMAL(12,2) NOT NULL,   -- positive = contact owes more, negative = balance reduced
  created_at     TEXT NOT NULL DEFAULT (strftime('%Y-%m-%dT%H:%M:%fZ','now'))
);


-- ============================================================================
-- CATALOG
-- ============================================================================
CREATE TABLE categories (
  id          INTEGER PRIMARY KEY AUTOINCREMENT,
  business_id INTEGER NOT NULL REFERENCES businesses(id) ON DELETE CASCADE,
  name        TEXT NOT NULL,
  created_at  TEXT NOT NULL DEFAULT (strftime('%Y-%m-%dT%H:%M:%fZ','now')),
  CONSTRAINT uq_categories_business_name UNIQUE (business_id, name)
);

CREATE TABLE tax_rates (
  id              INTEGER PRIMARY KEY AUTOINCREMENT,
  business_id     INTEGER NOT NULL REFERENCES businesses(id) ON DELETE CASCADE,
  name            TEXT NOT NULL,
  rate_percentage DECIMAL(5,2) NOT NULL CHECK (rate_percentage >= 0 AND rate_percentage <= 100),
  is_active       INTEGER NOT NULL DEFAULT 1 CHECK (is_active IN (0,1)),
  CONSTRAINT uq_tax_rates_business_name UNIQUE (business_id, name)
);

CREATE TABLE products (
  id                     INTEGER PRIMARY KEY AUTOINCREMENT,
  business_id            INTEGER NOT NULL REFERENCES businesses(id) ON DELETE CASCADE,
  name                   TEXT NOT NULL,
  sku                    TEXT NOT NULL,             -- auto-generate in app code if left blank
  barcode_type           TEXT CHECK (barcode_type IN ('EAN13','EAN8','CODE128','CODE39','QR','UPCA')),
  barcode_number         TEXT,
  category_id            INTEGER REFERENCES categories(id) ON DELETE RESTRICT,
  alert_quantity         DECIMAL(12,2),
  description            TEXT,
  not_for_selling        INTEGER NOT NULL DEFAULT 0 CHECK (not_for_selling IN (0,1)),
  rack_row_position      TEXT,
  applicable_tax_id      INTEGER REFERENCES tax_rates(id) ON DELETE SET NULL,
  selling_price_tax_type TEXT CHECK (selling_price_tax_type IN ('inclusive','exclusive')),
  product_type           TEXT DEFAULT 'single' CHECK (product_type IN ('single','variable','combo')),
  cost_price             DECIMAL(12,2) NOT NULL CHECK (cost_price >= 0),
  default_selling_price  DECIMAL(12,2) NOT NULL CHECK (default_selling_price >= 0),
  warranty_info          TEXT,
  is_active              INTEGER NOT NULL DEFAULT 1 CHECK (is_active IN (0,1)),
  created_at             TEXT NOT NULL DEFAULT (strftime('%Y-%m-%dT%H:%M:%fZ','now')),
  CONSTRAINT uq_products_business_sku     UNIQUE (business_id, sku),
  CONSTRAINT uq_products_business_barcode UNIQUE (business_id, barcode_number)
);

-- case-insensitive unique product name per business (was a stray statement
-- inside CREATE TABLE in the source; it must be a separate index).
-- NOTE: SQLite LOWER() only folds ASCII letters.
CREATE UNIQUE INDEX uq_products_business_name ON products (business_id, LOWER(TRIM(name)));

CREATE TABLE product_locations (        -- which location(s) stock this product
  product_id  INTEGER NOT NULL REFERENCES products(id)  ON DELETE CASCADE,
  location_id INTEGER NOT NULL REFERENCES locations(id) ON DELETE CASCADE,
  PRIMARY KEY (product_id, location_id)
);

CREATE TABLE product_variants (          -- for product_type = 'variable'
  id            INTEGER PRIMARY KEY AUTOINCREMENT,
  product_id    INTEGER NOT NULL REFERENCES products(id)   ON DELETE CASCADE,
  business_id   INTEGER NOT NULL REFERENCES businesses(id) ON DELETE CASCADE,
  attributes    TEXT NOT NULL DEFAULT '{}' CHECK (json_valid(attributes)),   -- e.g. {"size":"L","color":"Red"}
  sku           TEXT,
  cost_price    DECIMAL(12,2),
  selling_price DECIMAL(12,2),
  created_at    TEXT NOT NULL DEFAULT (strftime('%Y-%m-%dT%H:%M:%fZ','now'))
);

CREATE TABLE product_combo_items (       -- for product_type = 'combo'
  id                   INTEGER PRIMARY KEY AUTOINCREMENT,
  combo_product_id     INTEGER NOT NULL REFERENCES products(id) ON DELETE CASCADE,
  component_product_id INTEGER NOT NULL REFERENCES products(id) ON DELETE RESTRICT,
  quantity             DECIMAL(12,2) NOT NULL CHECK (quantity > 0),
  CONSTRAINT chk_combo_not_self CHECK (combo_product_id <> component_product_id)
);


-- ============================================================================
-- STOCK LEDGER
-- ============================================================================
CREATE TABLE stock_ledger (
  id             INTEGER PRIMARY KEY AUTOINCREMENT,
  business_id    INTEGER NOT NULL REFERENCES businesses(id) ON DELETE CASCADE,
  product_id     INTEGER NOT NULL REFERENCES products(id)   ON DELETE RESTRICT,
  variant_id     INTEGER REFERENCES product_variants(id)    ON DELETE SET NULL,
  location_id    INTEGER NOT NULL REFERENCES locations(id)  ON DELETE RESTRICT,
  change_qty     DECIMAL(12,2) NOT NULL,       -- positive = stock in, negative = stock out
  reason         TEXT NOT NULL CHECK (reason IN
                   ('purchase','sale','purchase_return','sell_return','adjustment',
                    'transfer','sale_edit_reversal','sale_edit','purchase_edit')),
  reference_type TEXT,                         -- 'purchase','sale','purchase_return','sell_return', etc.
  reference_id   INTEGER,                      -- polymorphic (no FK)
  created_by     TEXT REFERENCES users(id) ON DELETE SET NULL,
  created_at     TEXT NOT NULL DEFAULT (strftime('%Y-%m-%dT%H:%M:%fZ','now')),
  unit_cost      DECIMAL(12,2)                 -- FIFO layer cost
);


-- ============================================================================
-- REGISTERS (cash drawer)  — defined before sales/returns/expenses that FK to it
-- ============================================================================
CREATE TABLE registers (
  id           INTEGER PRIMARY KEY AUTOINCREMENT,
  business_id  INTEGER NOT NULL REFERENCES businesses(id) ON DELETE CASCADE,
  location_id  INTEGER NOT NULL REFERENCES locations(id)  ON DELETE RESTRICT,
  user_id      TEXT    NOT NULL REFERENCES users(id)      ON DELETE RESTRICT,
  opened_at    TEXT NOT NULL DEFAULT (strftime('%Y-%m-%dT%H:%M:%fZ','now')),
  closed_at    TEXT,
  opening_cash DECIMAL(12,2) NOT NULL DEFAULT 0 CHECK (opening_cash >= 0),
  closing_cash DECIMAL(12,2) CHECK (closing_cash IS NULL OR closing_cash >= 0),
  status       TEXT NOT NULL DEFAULT 'open' CHECK (status IN ('open','closed'))
);

-- One OPEN register per user (final state after the "per-user" migration).
CREATE UNIQUE INDEX uq_registers_one_open_per_user ON registers (user_id) WHERE status = 'open';
CREATE INDEX idx_registers_business_location_status ON registers (business_id, location_id, status);
CREATE INDEX idx_registers_business_user_status     ON registers (business_id, user_id, status);


-- ============================================================================
-- PURCHASES
-- ============================================================================
CREATE TABLE purchases (
  id                      INTEGER PRIMARY KEY AUTOINCREMENT,
  business_id             INTEGER NOT NULL REFERENCES businesses(id) ON DELETE CASCADE,
  location_id             INTEGER NOT NULL REFERENCES locations(id)  ON DELETE RESTRICT,
  supplier_id             INTEGER REFERENCES contacts(id)            ON DELETE RESTRICT,  -- NULL = unspecified/cash supplier
  purchase_date           TEXT NOT NULL DEFAULT (date('now','localtime')),
  purchase_status         TEXT NOT NULL DEFAULT 'draft' CHECK (purchase_status IN ('draft','received','cancelled')),
  pay_term                TEXT,
  supplier_invoice_number TEXT,
  subtotal                DECIMAL(12,2) NOT NULL DEFAULT 0,
  discount_type           TEXT CHECK (discount_type IN ('fixed','percentage')),
  discount_amount         DECIMAL(12,2) NOT NULL DEFAULT 0,
  tax_amount              DECIMAL(12,2) NOT NULL DEFAULT 0,
  shipping_charges        DECIMAL(12,2) NOT NULL DEFAULT 0,
  grand_total             DECIMAL(12,2) NOT NULL DEFAULT 0,
  advance_payment         DECIMAL(12,2) NOT NULL DEFAULT 0,
  payment_method          TEXT,
  payment_note            TEXT,
  paid_on                 TEXT,
  is_active               INTEGER NOT NULL DEFAULT 1 CHECK (is_active IN (0,1)),   -- soft delete
  created_by              TEXT REFERENCES users(id) ON DELETE SET NULL,
  created_at              TEXT NOT NULL DEFAULT (strftime('%Y-%m-%dT%H:%M:%fZ','now'))
);

CREATE TABLE purchase_items (
  id              INTEGER PRIMARY KEY AUTOINCREMENT,
  purchase_id     INTEGER NOT NULL REFERENCES purchases(id) ON DELETE CASCADE,
  product_id      INTEGER NOT NULL REFERENCES products(id)  ON DELETE RESTRICT,
  variant_id      INTEGER REFERENCES product_variants(id)   ON DELETE RESTRICT,
  quantity        DECIMAL(12,2) NOT NULL CHECK (quantity > 0),
  unit_cost       DECIMAL(12,2) NOT NULL CHECK (unit_cost >= 0),
  discount_type   TEXT CHECK (discount_type IN ('fixed','percentage')),
  discount_amount DECIMAL(12,2) NOT NULL DEFAULT 0,
  tax_id          INTEGER REFERENCES tax_rates(id) ON DELETE SET NULL,
  line_total      DECIMAL(12,2) NOT NULL
);

CREATE TABLE purchase_returns (
  id           INTEGER PRIMARY KEY AUTOINCREMENT,
  business_id  INTEGER NOT NULL REFERENCES businesses(id) ON DELETE CASCADE,
  purchase_id  INTEGER NOT NULL REFERENCES purchases(id)  ON DELETE RESTRICT,
  return_date  TEXT NOT NULL DEFAULT (date('now','localtime')),
  reason       TEXT,
  total_amount DECIMAL(12,2) NOT NULL,
  created_by   TEXT REFERENCES users(id) ON DELETE SET NULL,
  created_at   TEXT NOT NULL DEFAULT (strftime('%Y-%m-%dT%H:%M:%fZ','now'))
);

CREATE TABLE purchase_return_items (
  id                 INTEGER PRIMARY KEY AUTOINCREMENT,
  purchase_return_id INTEGER NOT NULL REFERENCES purchase_returns(id) ON DELETE CASCADE,
  purchase_item_id   INTEGER NOT NULL REFERENCES purchase_items(id)   ON DELETE RESTRICT,
  quantity_returned  DECIMAL(12,2) NOT NULL CHECK (quantity_returned > 0),
  amount             DECIMAL(12,2) NOT NULL
);


-- ============================================================================
-- SALES
-- ============================================================================
CREATE TABLE sales (
  id               INTEGER PRIMARY KEY AUTOINCREMENT,
  business_id      INTEGER NOT NULL REFERENCES businesses(id) ON DELETE CASCADE,
  location_id      INTEGER NOT NULL REFERENCES locations(id)  ON DELETE RESTRICT,
  customer_id      INTEGER REFERENCES contacts(id)            ON DELETE RESTRICT,   -- NULL = walk-in
  sales_agent_id   TEXT REFERENCES users(id) ON DELETE SET NULL,
  channel          TEXT NOT NULL DEFAULT 'manual' CHECK (channel IN ('pos','manual')),
  sale_date        TEXT NOT NULL DEFAULT (date('now','localtime')),
  status           TEXT NOT NULL DEFAULT 'draft' CHECK (status IN
                     ('draft','quotation','confirmed','shipped','returned','partially_returned')),
  pay_term         TEXT,
  subtotal         DECIMAL(12,2) NOT NULL DEFAULT 0,
  discount_type    TEXT CHECK (discount_type IN ('fixed','percentage')),
  discount_amount  DECIMAL(12,2) NOT NULL DEFAULT 0,
  tax_amount       DECIMAL(12,2) NOT NULL DEFAULT 0,
  shipping_charges DECIMAL(12,2) NOT NULL DEFAULT 0,
  grand_total      DECIMAL(12,2) NOT NULL DEFAULT 0,
  payment_method   TEXT,
  payment_note     TEXT,
  paid_amount      DECIMAL(12,2) NOT NULL DEFAULT 0,
  due_amount       DECIMAL(12,2) NOT NULL DEFAULT 0,
  is_active        INTEGER NOT NULL DEFAULT 1 CHECK (is_active IN (0,1)),   -- soft delete
  created_by       TEXT REFERENCES users(id) ON DELETE SET NULL,
  created_at       TEXT NOT NULL DEFAULT (strftime('%Y-%m-%dT%H:%M:%fZ','now')),
  staff_note       TEXT,
  register_id      INTEGER REFERENCES registers(id) ON DELETE SET NULL
);

CREATE TABLE sale_items (
  id              INTEGER PRIMARY KEY AUTOINCREMENT,
  sale_id         INTEGER NOT NULL REFERENCES sales(id)    ON DELETE CASCADE,
  product_id      INTEGER NOT NULL REFERENCES products(id) ON DELETE RESTRICT,
  variant_id      INTEGER REFERENCES product_variants(id)  ON DELETE RESTRICT,
  quantity        DECIMAL(12,2) NOT NULL CHECK (quantity > 0),
  unit_price      DECIMAL(12,2) NOT NULL CHECK (unit_price >= 0),
  discount_type   TEXT CHECK (discount_type IN ('fixed','percentage')),
  discount_amount DECIMAL(12,2) NOT NULL DEFAULT 0,
  tax_id          INTEGER REFERENCES tax_rates(id) ON DELETE SET NULL,
  line_total      DECIMAL(12,2) NOT NULL,
  unit_cost       NUMERIC          -- FIFO cost captured at sale time
);

CREATE TABLE sell_returns (
  id           INTEGER PRIMARY KEY AUTOINCREMENT,
  business_id  INTEGER NOT NULL REFERENCES businesses(id) ON DELETE CASCADE,
  sale_id      INTEGER NOT NULL REFERENCES sales(id)      ON DELETE RESTRICT,
  return_date  TEXT NOT NULL DEFAULT (date('now','localtime')),
  reason       TEXT,
  total_amount DECIMAL(12,2) NOT NULL,
  created_by   TEXT REFERENCES users(id) ON DELETE SET NULL,
  created_at   TEXT NOT NULL DEFAULT (strftime('%Y-%m-%dT%H:%M:%fZ','now')),
  register_id  INTEGER REFERENCES registers(id) ON DELETE SET NULL
);

CREATE TABLE sell_return_items (
  id                INTEGER PRIMARY KEY AUTOINCREMENT,
  sell_return_id    INTEGER NOT NULL REFERENCES sell_returns(id) ON DELETE CASCADE,
  sale_item_id      INTEGER NOT NULL REFERENCES sale_items(id)   ON DELETE RESTRICT,
  quantity_returned DECIMAL(12,2) NOT NULL CHECK (quantity_returned > 0),
  amount            DECIMAL(12,2) NOT NULL
);

CREATE TABLE shipments (
  id              INTEGER PRIMARY KEY AUTOINCREMENT,
  sale_id         INTEGER NOT NULL REFERENCES sales(id) ON DELETE CASCADE,
  shipment_status TEXT NOT NULL DEFAULT 'pending',
  shipped_date    TEXT,
  tracking_info   TEXT,
  created_at      TEXT NOT NULL DEFAULT (strftime('%Y-%m-%dT%H:%M:%fZ','now'))
);

