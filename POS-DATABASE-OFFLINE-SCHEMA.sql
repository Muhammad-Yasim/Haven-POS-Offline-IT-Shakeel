-- ============================================================================
-- 001_initial_schema.sql  —  Offline POS (Electron + better-sqlite3)
-- ============================================================================
-- Converted from the PostgreSQL / Supabase schema (final state, including the
-- registers migrations). This file is meant to be run by the migration runner
-- inside ONE transaction on a brand-new database.
--
-- Connection-level settings (NOT in this file; set in electron/database/db.js
-- right after opening the DB, because PRAGMA foreign_keys is a no-op inside a
-- transaction and must be set on every connection):
--     PRAGMA foreign_keys = ON;
--     PRAGMA journal_mode = WAL;
--     PRAGMA synchronous  = NORMAL;
--
-- TYPE MAPPING
--   INT GENERATED ALWAYS AS IDENTITY  -> INTEGER PRIMARY KEY AUTOINCREMENT
--   UUID                              -> TEXT (app generates crypto.randomUUID())
--   ENUM                              -> TEXT + CHECK (col IN (...))
--   BOOLEAN                           -> INTEGER 0/1 + CHECK (col IN (0,1))
--   DECIMAL(12,2)                     -> DECIMAL(12,2) (NUMERIC affinity; SQLite does
--                                        not enforce precision -> round in app code)
--   JSONB                             -> TEXT + CHECK (json_valid(col))
--   DATE                              -> TEXT 'YYYY-MM-DD'
--   TIMESTAMPTZ                       -> TEXT ISO-8601 UTC 'YYYY-MM-DDTHH:MM:SS.sssZ'
--   RLS / current_business_id()       -> removed (enforced in the Electron layer)
-- ============================================================================


-- DEPLOYMENT MODEL (drives several choices below)
--   * ONE business and ONE owner per installation.
--   * No self-registration. The developer provisions the business + owner and
--     hands the credentials to the client.
--   * No user-management module yet. Anything that only exists to support
--     multiple staff is COMMENTED OUT under the marker "DEFERRED: user mgmt".
--     To bring it back later, add a NEW numbered migration (never edit this
--     file once it has shipped to a client).
-- ============================================================================


-- ============================================================================
-- BUSINESSES  (one row per installation)
-- ============================================================================
CREATE TABLE businesses (
  id                    INTEGER PRIMARY KEY AUTOINCREMENT CHECK (id = 1),  -- single business per install
  business_name         TEXT NOT NULL,
  business_start_date   TEXT,
  currency              TEXT NOT NULL,
  website_link          TEXT,
  contact_number        TEXT NOT NULL,
  alternate_contact     TEXT,
  country               TEXT NOT NULL,
  state                 TEXT,
  city                  TEXT NOT NULL,
  zip_code              TEXT,
  landmark              TEXT,
  time_zone             TEXT NOT NULL,
  -- DEFERRED: registration/referral program (not applicable to dev-provisioned offline installs)
  -- referral_code         TEXT CHECK (referral_code IS NULL OR length(referral_code) <= 8),
  status                TEXT NOT NULL DEFAULT 'active'
                          CHECK (status IN ('trial','active','inactive')),
  settings              TEXT NOT NULL DEFAULT '{}' CHECK (json_valid(settings)),
  created_at            TEXT NOT NULL DEFAULT (strftime('%Y-%m-%dT%H:%M:%fZ','now'))
);

CREATE TABLE locations (
  id          INTEGER PRIMARY KEY AUTOINCREMENT,
  business_id INTEGER NOT NULL REFERENCES businesses(id) ON DELETE CASCADE,
  name        TEXT NOT NULL,
  address     TEXT,
  city        TEXT,
  country     TEXT,
  is_active   INTEGER NOT NULL DEFAULT 1 CHECK (is_active IN (0,1)),
  created_at  TEXT NOT NULL DEFAULT (strftime('%Y-%m-%dT%H:%M:%fZ','now')),
  CONSTRAINT uq_locations_business_name UNIQUE (business_id, name)
);


